public static class Constants
{
    /// <summary>
    /// Multi-version support
    /// </summary>
    public static readonly string[] VersionDependent = [".h", ".cpp", ".c"];

    /// <summary>
    /// Keep both
    /// </summary>
    public static readonly string[] OldProjectFiles = [".dsp", ".dsw"];

